function seasonal(name, title, bpm, lead, roots, perBar = 4) {
  const bass = [];
  for (const root of roots) {
    for (let i = 0; i < perBar; i += 1) bass.push(i % 2 === 0 ? root : 0);
  }
  return { name, title, beat: 60 / bpm, hat: false, bass, lead };
}

